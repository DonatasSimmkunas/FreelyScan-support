import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const names=['app.js','crawler.js','counter.js','mottos.js','hologram.js','styles.css','mottos.css'];
const assets={};
for(const name of names){
  let content=await readFile(path.join(root,'public',name),'utf8');
  if(name==='crawler.js')content=content.replace(/from '\.\/app(?:\.[a-f0-9]{12})?\.js(?:\?[^']*)?'/,`from './${assets['app.js']}'`);
  const digest=createHash('sha256').update(content).digest('hex').slice(0,12);
  const target=name.replace(/\.(js|css)$/,`.${digest}.$1`);
  await writeFile(path.join(root,'public',target),content);
  assets[name]=target;
}
let html=await readFile(path.join(root,'public/index.html'),'utf8');
for(const [source,target]of Object.entries(assets)){
  const [base,extension]=source.split('.');
  const pattern=new RegExp(`/vip/${base}(?:\\.[a-f0-9]{12})?\\.${extension}(?:\\?[^"\\s]*)?`,'g');
  if(!pattern.test(html))throw new Error(`Missing asset: ${source}`);
  html=html.replace(pattern,`/vip/${target}`);
}
await writeFile(path.join(root,'public/index.html'),html);
await writeFile(path.join(root,'lib/public-assets.mjs'),'// Generated by scripts/build-public-assets.mjs. Public assets only.\nexport const publicAssets='+JSON.stringify(Object.values(assets))+';\n');
console.log(JSON.stringify(assets));
